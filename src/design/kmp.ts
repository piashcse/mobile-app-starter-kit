import path from 'path';
import fs from 'fs-extra';
import {
  componentTokens,
  darkColors,
  lightColors,
  radii,
  spacing,
  typography,
} from './tokens.js';
import { catalogs, supportedLocales } from './strings.js';

export async function writeKmpDesign(outputDir: string): Promise<void> {
  const themeDir = path.join(
    outputDir,
    'composeApp',
    'src',
    'commonMain',
    'kotlin',
    'core',
    'theme'
  );
  await fs.ensureDir(themeDir);

  const kmpColor = (name: string, value: string) =>
    `    val ${name} = Color(0xFF${value.slice(1).toUpperCase()})`;

  const colors = `package core.theme

import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

// Generated by mobile-app-starter-kit from design-tokens.json.
object AppColors {
${kmpColor('Primary', darkColors.primary)}
${kmpColor('PrimaryLight', darkColors.primaryLight)}
${kmpColor('PrimaryPressed', darkColors.primaryPressed)}
${kmpColor('PrimaryDark', darkColors.primaryPressed)}
${kmpColor('OnPrimary', darkColors.onPrimary)}
${kmpColor('Accent', darkColors.accent)}
${kmpColor('AccentLight', darkColors.accentLight)}
${kmpColor('Background', darkColors.background)}
${kmpColor('Surface', darkColors.surface)}
${kmpColor('SurfaceAlt', darkColors.surfaceAlt)}
${kmpColor('SurfaceLight', darkColors.surfaceAlt)}
${kmpColor('TextPrimary', darkColors.textPrimary)}
${kmpColor('TextSecondary', darkColors.textSecondary)}
${kmpColor('TextMuted', darkColors.textMuted)}
${kmpColor('Border', darkColors.border)}
${kmpColor('BorderStrong', darkColors.borderLight)}
${kmpColor('Success', darkColors.success)}
${kmpColor('Warning', darkColors.warning)}
${kmpColor('Error', darkColors.error)}
${kmpColor('Info', darkColors.info)}
${kmpColor('GradientStart', darkColors.gradientStart)}
${kmpColor('GradientEnd', darkColors.gradientEnd)}

    // Light palette
${kmpColor('BackgroundLight', lightColors.background)}
${kmpColor('SurfaceLightCard', lightColors.surface)}
${kmpColor('SurfaceAltLight', lightColors.surfaceAlt)}
${kmpColor('TextPrimaryLight', lightColors.textPrimary)}
${kmpColor('TextSecondaryLight', lightColors.textSecondary)}
${kmpColor('TextMutedLight', lightColors.textMuted)}
${kmpColor('BorderLight', lightColors.border)}
${kmpColor('OnPrimaryLight', lightColors.onPrimary)}
}

val LightColorScheme = lightColorScheme(
    primary = AppColors.Primary,
    onPrimary = AppColors.OnPrimaryLight,
    secondary = AppColors.Accent,
    background = AppColors.BackgroundLight,
    onBackground = AppColors.TextPrimaryLight,
    surface = AppColors.SurfaceLightCard,
    onSurface = AppColors.TextPrimaryLight,
    surfaceVariant = AppColors.SurfaceAltLight,
    onSurfaceVariant = AppColors.TextSecondaryLight,
    outlineVariant = AppColors.BorderLight,
    error = AppColors.Error,
    onError = AppColors.OnPrimaryLight,
)

val DarkColorScheme = darkColorScheme(
    primary = AppColors.Primary,
    onPrimary = AppColors.OnPrimary,
    secondary = AppColors.Accent,
    background = AppColors.Background,
    onBackground = AppColors.TextPrimary,
    surface = AppColors.Surface,
    onSurface = AppColors.TextPrimary,
    surfaceVariant = AppColors.SurfaceAlt,
    onSurfaceVariant = AppColors.TextSecondary,
    outlineVariant = AppColors.Border,
    error = AppColors.Error,
    onError = AppColors.OnPrimary,
)
`;
  await fs.writeFile(path.join(themeDir, 'AppColors.kt'), colors, 'utf-8');

  const typeEntries = Object.entries(typography)
    .map(
      ([name, style]) =>
        `    val ${name} = TextStyle(fontSize = ${style.size}.sp, lineHeight = ${style.lineHeight}.sp, fontWeight = FontWeight.${weightName(style.weight)}, letterSpacing = ${style.letterSpacing ?? 0}.sp)`
    )
    .join('\n');

  const designTokens = `package core.theme

import androidx.compose.material3.Typography
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

// Generated by mobile-app-starter-kit from design-tokens.json.
object AppSpacing {
    val xs = ${spacing.xs}.dp
    val sm = ${spacing.sm}.dp
    val md = ${spacing.md}.dp
    val lg = ${spacing.lg}.dp
    val xl = ${spacing.xl}.dp
    val xxl = ${spacing.xxl}.dp
}

object AppRadii {
    val sm = ${radii.sm}.dp
    val md = ${radii.md}.dp
    val lg = ${radii.lg}.dp
    val xl = ${radii.xl}.dp
}

object AppSizes {
    val buttonHeight = ${componentTokens.buttonHeight}.dp
    val buttonRadius = ${componentTokens.buttonRadius}.dp
    val inputHeight = ${componentTokens.inputHeight}.dp
    val cardPadding = ${componentTokens.cardPadding}.dp
    val screenPadding = ${componentTokens.screenPadding}.dp
    val sectionGap = ${componentTokens.sectionGap}.dp
    val icon = ${componentTokens.iconSize}.dp
    val touchTarget = ${componentTokens.touchTarget}.dp
}

object AppType {
${typeEntries}
}

val AppTypography = Typography(
    headlineLarge = AppType.display.copy(fontWeight = FontWeight.Bold),
    headlineMedium = AppType.title.copy(fontWeight = FontWeight.Bold),
    headlineSmall = AppType.heading.copy(fontWeight = FontWeight.SemiBold),
    titleMedium = AppType.subtitle.copy(fontWeight = FontWeight.SemiBold),
    bodyLarge = AppType.body,
    bodyMedium = AppType.bodySmall,
    bodySmall = AppType.caption,
    labelLarge = AppType.button,
    labelMedium = AppType.label,
)
`;
  await fs.writeFile(
    path.join(themeDir, 'DesignTokens.kt'),
    designTokens,
    'utf-8'
  );

  const resourcesDir = path.join(
    outputDir,
    'composeApp',
    'src',
    'commonMain',
    'composeResources'
  );

  const escapeResource = (value: string): string =>
    value
      .replace(/\\/g, '\\\\')
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '\\"')
      .replace(/'/g, "\\'")
      .replace(/\{\w+\}/g, '%s')
      .replace(/\n/g, '\\n');

  const writeStringsXml = async (
    folder: string,
    values: Record<string, string>
  ) => {
    const dir = path.join(resourcesDir, folder);
    await fs.ensureDir(dir);
    const entries = Object.entries(values)
      .map(
        ([key, value]) =>
          `    <string name="${key}">${escapeResource(value)}</string>`
      )
      .join('\n');
    await fs.writeFile(
      path.join(dir, 'strings.xml'),
      `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n${entries}\n</resources>\n`,
      'utf-8'
    );
  };

  const englishResources: Record<string, string> = {};
  for (const [key, value] of Object.entries(catalogs.en)) {
    englishResources[resourceName(key)] = value;
  }
  const spanishResources: Record<string, string> = {};
  for (const [key, value] of Object.entries(catalogs.es)) {
    spanishResources[resourceName(key)] = value;
  }

  await writeStringsXml('values', englishResources);
  await writeStringsXml('values-es', spanishResources);

  const i18nDir = path.join(
    outputDir,
    'composeApp',
    'src',
    'commonMain',
    'kotlin',
    'core',
    'i18n'
  );
  await fs.ensureDir(i18nDir);

  const languageButtons = supportedLocales
    .map((locale) => {
      const key = resourceName(`common.language${locale.label}`);
      return `        TextButton(onClick = { controller.selectLocale("${locale.code}") }) {
            Text(
                stringResource(Res.string.${key}),
                color = if (controller.locale == "${locale.code}") {
                    MaterialTheme.colorScheme.primary
                } else {
                    MaterialTheme.colorScheme.onSurfaceVariant
                },
                fontWeight = if (controller.locale == "${locale.code}") {
                    FontWeight.SemiBold
                } else {
                    FontWeight.Normal
                },
            )
        }`;
    })
    .join('\n');

  await fs.writeFile(
    path.join(i18nDir, 'LanguageSwitcher.kt'),
    `package core.i18n

import androidx.compose.foundation.layout.Arrangement
import androidx.compose.foundation.layout.Row
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Text
import androidx.compose.material3.TextButton
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import app.generated.resources.Res
import app.generated.resources.common_language
import ${supportedLocales
      .map(
        (l) =>
          `app.generated.resources.${resourceName(`common.language${l.label}`)}`
      )
      .join('\nimport ')}
import org.jetbrains.compose.resources.stringResource

@Composable
fun LanguageSwitcher(modifier: Modifier = Modifier) {
    val controller = LocalLocaleController.current

    Row(
        modifier = modifier,
        horizontalArrangement = Arrangement.spacedBy(4.dp),
    ) {
        Text(
            stringResource(Res.string.common_language),
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
${languageButtons}
    }
}
`,
    'utf-8'
  );
}

function resourceName(key: string): string {
  return key
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .toLowerCase()
    .replace(/^_+|_+$/g, '');
}

function weightName(weight: string): string {
  switch (weight) {
    case '700':
      return 'Bold';
    case '600':
      return 'SemiBold';
    case '500':
      return 'Medium';
    default:
      return 'Normal';
  }
}
