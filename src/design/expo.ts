import path from 'path';
import fs from 'fs-extra';
import {
  componentTokens,
  darkColors,
  lightColors,
  motion,
  radii,
  spacing,
  typography,
  type ColorRole,
} from './tokens.js';
import { catalogs, supportedLocales } from './strings.js';

export async function writeExpoDesign(outputDir: string): Promise<void> {
  const themeDir = path.join(outputDir, 'src', 'theme');
  await fs.ensureDir(themeDir);

  const palette = (
    name: string,
    p: ColorRole,
    typed: boolean
  ) => `export const ${name}${typed ? ': AppColors' : ''} = {
  primary: '${p.primary}',
  primaryLight: '${p.primaryLight}',
  primaryDark: '${p.primaryPressed}',
  onPrimary: '${p.onPrimary}',
  accent: '${p.accent}',
  accentLight: '${p.accentLight}',
  background: '${p.background}',
  surface: '${p.surface}',
  surfaceLight: '${p.surfaceAlt}',
  surfaceAlt: '${p.surfaceAlt}',
  textPrimary: '${p.textPrimary}',
  textSecondary: '${p.textSecondary}',
  textMuted: '${p.textMuted}',
  border: '${p.border}',
  borderLight: '${p.borderLight}',
  success: '${p.success}',
  warning: '${p.warning}',
  error: '${p.error}',
  info: '${p.info}',
  overlay: '${p.overlay}',
  gradientStart: '${p.gradientStart}',
  gradientEnd: '${p.gradientEnd}',
} as const;`;

  const colors = `// Generated by mobile-app-starter-kit from design-tokens.json.
${palette('darkColors', darkColors, false)}

export type AppColors = Record<keyof typeof darkColors, string>;

${palette('lightColors', lightColors, true)}

export const ThemeColors: { light: AppColors; dark: AppColors } = {
  light: lightColors,
  dark: darkColors as AppColors,
};

export type ColorKey = keyof AppColors;
`;
  await fs.writeFile(path.join(themeDir, 'colors.ts'), colors, 'utf-8');

  const textStyles: Record<string, string> = {
    h1: 'display',
    h2: 'title',
    h3: 'heading',
    subtitle: 'subtitle',
    body: 'body',
    bodySmall: 'bodySmall',
    caption: 'caption',
    button: 'button',
    label: 'label',
  };

  const typographyEntries = Object.entries(textStyles)
    .map(([styleName, tokenName]) => {
      const style = typography[tokenName as keyof typeof typography];
      return `  ${styleName}: { fontSize: ${style.size}, lineHeight: ${
        style.lineHeight
      }, fontWeight: '${style.weight}'${
        style.letterSpacing ? `, letterSpacing: ${style.letterSpacing}` : ''
      } },`;
    })
    .join('\n');

  const tokens = `// Generated by mobile-app-starter-kit from design-tokens.json.
import { StyleSheet } from 'react-native';

export const spacing = {
${Object.entries(spacing)
  .map(([key, value]) => `  ${key}: ${value},`)
  .join('\n')}
} as const;

export const borderRadius = {
${Object.entries(radii)
  .map(([key, value]) => `  ${key}: ${value},`)
  .join('\n')}
} as const;

export const components = {
${Object.entries(componentTokens)
  .map(([key, value]) => `  ${key}: ${value},`)
  .join('\n')}
} as const;

export const motion = {
${Object.entries(motion)
  .map(([key, value]) => `  ${key}: ${value},`)
  .join('\n')}
} as const;

export const typography = StyleSheet.create({
${typographyEntries}
});
`;
  await fs.writeFile(path.join(themeDir, 'tokens.ts'), tokens, 'utf-8');

  await fs.writeFile(
    path.join(themeDir, 'spacing.ts'),
    `export { spacing, borderRadius, components, motion } from './tokens';\n`,
    'utf-8'
  );
  await fs.writeFile(
    path.join(themeDir, 'typography.ts'),
    `export { typography } from './tokens';\n`,
    'utf-8'
  );
  await fs.writeFile(
    path.join(themeDir, 'index.ts'),
    `export { ThemeColors, darkColors, lightColors } from './colors';
export type { AppColors, ColorKey } from './colors';
export { ThemeProvider, useAppTheme } from './ThemeProvider';
export { makeStyles } from './styles';
export {
  spacing,
  borderRadius,
  components,
  motion,
  typography,
} from './tokens';
`,
    'utf-8'
  );
}

export async function writeExpoI18n(outputDir: string): Promise<void> {
  const i18nDir = path.join(outputDir, 'src', 'i18n');
  await fs.ensureDir(i18nDir);

  const catalogSource = `// Generated by mobile-app-starter-kit from the shared string catalog.
export const supportedLocales = ${JSON.stringify(supportedLocales, null, 2)} as const;

export type LocaleCode = (typeof supportedLocales)[number]['code'];

export const catalogs = ${JSON.stringify(catalogs, null, 2)} as const;

export type TranslationKey = keyof (typeof catalogs)['en'];

export function translate(
  locale: LocaleCode,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  const template = catalogs[locale]?.[key] ?? catalogs.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\\{(\\w+)\\}/g, (match, name: string) =>
    String(params[name] ?? match)
  );
}
`;
  await fs.writeFile(path.join(i18nDir, 'catalogs.ts'), catalogSource, 'utf-8');
  await fs.writeFile(
    path.join(i18nDir, 'index.ts'),
    `export { I18nProvider, useTranslation } from './I18nProvider';
export {
  catalogs,
  supportedLocales,
  translate,
  type LocaleCode,
  type TranslationKey,
} from './catalogs';
`,
    'utf-8'
  );
}

