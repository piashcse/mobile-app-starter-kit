const dartColor = (name: string, value: string) =>
  `  static const ${name} = Color(0xFF${value.slice(1).toUpperCase()});`;

export async function writeFlutterDesign(outputDir: string): Promise<void> {
  const themeDir = path.join(outputDir, 'lib', 'core', 'theme');
  await fs.ensureDir(themeDir);

  const dartColors = `// Generated by mobile-app-starter-kit from design-tokens.json.
import 'package:flutter/material.dart';

class AppColors {
  AppColors._();

  // Dark palette
${dartColor('primary', darkColors.primary)}
${dartColor('primaryLight', darkColors.primaryLight)}
${dartColor('primaryPressed', darkColors.primaryPressed)}
${dartColor('primaryDark', darkColors.primaryPressed)}
${dartColor('onPrimary', darkColors.onPrimary)}
${dartColor('accent', darkColors.accent)}
${dartColor('accentLight', darkColors.accentLight)}
${dartColor('background', darkColors.background)}
${dartColor('surface', darkColors.surface)}
${dartColor('surfaceLight', darkColors.surfaceAlt)}
${dartColor('surfaceAlt', darkColors.surfaceAlt)}
${dartColor('textPrimary', darkColors.textPrimary)}
${dartColor('textSecondary', darkColors.textSecondary)}
${dartColor('textMuted', darkColors.textMuted)}
${dartColor('border', darkColors.border)}
${dartColor('borderStrong', darkColors.borderLight)}
${dartColor('success', darkColors.success)}
${dartColor('warning', darkColors.warning)}
${dartColor('error', darkColors.error)}
${dartColor('info', darkColors.info)}
${dartColor('gradientStart', darkColors.gradientStart)}
${dartColor('gradientEnd', darkColors.gradientEnd)}

  // Light palette
${dartColor('backgroundLight', lightColors.background)}
${dartColor('surfaceLightCard', lightColors.surface)}
${dartColor('surfaceAltLight', lightColors.surfaceAlt)}
${dartColor('textPrimaryLight', lightColors.textPrimary)}
${dartColor('textSecondaryLight', lightColors.textSecondary)}
${dartColor('textMutedLight', lightColors.textMuted)}
${dartColor('borderLight', lightColors.border)}
${dartColor('onPrimaryLight', lightColors.onPrimary)}
}
`;
  await fs.writeFile(
    path.join(themeDir, 'app_colors.dart'),
    dartColors,
    'utf-8'
  );

  const typeEntries = Object.entries(typography)
    .map(
      ([name, style]) =>
        `  static const double ${name}Size = ${style.size};\n  static const double ${name}Height = ${style.lineHeight};`
    )
    .join('\n');

  const designTokens = `// Generated by mobile-app-starter-kit from design-tokens.json.
class AppSpacing {
  AppSpacing._();
${Object.entries(spacing)
  .map(([key, value]) => `  static const double ${key} = ${value};`)
  .join('\n')}
}

class AppRadii {
  AppRadii._();
${Object.entries(radii)
  .map(([key, value]) => `  static const double ${key} = ${value};`)
  .join('\n')}
}

class AppSizes {
  AppSizes._();
  static const double buttonHeight = ${componentTokens.buttonHeight};
  static const double buttonRadius = ${componentTokens.buttonRadius};
  static const double inputHeight = ${componentTokens.inputHeight};
  static const double inputBorderWidth = ${componentTokens.inputBorderWidth};
  static const double cardPadding = ${componentTokens.cardPadding};
  static const double screenPadding = ${componentTokens.screenPadding};
  static const double sectionGap = ${componentTokens.sectionGap};
  static const double icon = ${componentTokens.iconSize};
  static const double touchTarget = ${componentTokens.touchTarget};
}

class AppType {
  AppType._();
${typeEntries}
}
`;
  await fs.writeFile(
    path.join(themeDir, 'design_tokens.dart'),
    designTokens,
    'utf-8'
  );

  const l10nDir = path.join(outputDir, 'lib', 'core', 'l10n');
  await fs.ensureDir(l10nDir);

  const localizations = `// Generated by mobile-app-starter-kit from the shared string catalog.
import 'package:flutter/material.dart';

class AppLocalizations {
  AppLocalizations(this.locale);

  final Locale locale;

  static const supportedLocales = <Locale>[
${supportedLocales.map((l) => `    Locale('${l.code}'),`).join('\n')}
  ];

  static const Map<String, String> nativeLabels = {
${supportedLocales.map((l) => `    '${l.code}': '${l.nativeLabel}',`).join('\n')}
  };

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) {
    return Localizations.of<AppLocalizations>(context, AppLocalizations)!;
  }

  static const Map<String, Map<String, String>> _catalogs = {
${Object.entries(catalogs)
  .map(
    ([code, values]) =>
      `    '${code}': {\n${Object.entries(values)
        .map(([key, value]) => `      '${key}': ${JSON.stringify(value)},`)
        .join('\n')}\n    },`
  )
  .join('\n')}
  };

  String t(String key, [Map<String, String>? params]) {
    final values = _catalogs[locale.languageCode] ?? _catalogs['en']!;
    var message = values[key] ?? _catalogs['en']![key] ?? key;
    if (params != null) {
      params.forEach((name, value) {
        message = message.replaceAll('{$name}', value);
      });
    }
    return message;
  }
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => AppLocalizations.supportedLocales
      .any((supported) => supported.languageCode == locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) async =>
      AppLocalizations(locale);

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}
`;
  await fs.writeFile(
    path.join(l10nDir, 'app_localizations.dart'),
    localizations,
    'utf-8'
  );
}

